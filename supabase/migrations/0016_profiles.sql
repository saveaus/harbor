create or replace function private.record_audit_event() returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  data jsonb := to_jsonb(coalesce(new, old));
  target_workspace uuid := case when tg_table_name = 'workspaces' then (data ->> 'id')::uuid
                                else (data ->> 'workspace_id')::uuid end;
  actor uuid := auth.uid();
  -- Values that must never be copied into the log; the change is recorded without them.
  hidden constant text[] := array[
    'tax_file_number', 'bank_account_number', 'bank_bsb', 'super_member_number', 'token_hash', 'key_hash'
  ];
  diff jsonb;
begin
  -- Rows removed by a workspace deletion cascade have nowhere to be recorded.
  if not exists (select 1 from public.workspaces w where w.id = target_workspace) then
    return null;
  end if;
  if tg_op = 'UPDATE' then
    select jsonb_object_agg(
      n.key,
      case when n.key = any (hidden) then jsonb_build_object('hidden', true)
           else jsonb_build_object('from', o.value, 'to', n.value) end
    )
    into diff
    from jsonb_each(to_jsonb(new)) n
    join jsonb_each(to_jsonb(old)) o using (key)
    where n.value is distinct from o.value and n.key <> 'updated_at';
    if diff is null then
      return null;
    end if;
  end if;
  insert into public.audit_events (workspace_id, actor_id, actor_name, action, entity, entity_id, label, subject_id, changes)
  values (
    target_workspace,
    actor,
    coalesce((select m.display_name from public.workspace_members m
              where m.workspace_id = target_workspace and m.user_id = actor), ''),
    lower(tg_op),
    tg_table_name,
    case when data ? 'id' then (data ->> 'id')::uuid end,
    left(coalesce(
      nullif(data ->> 'name', ''),
      nullif(data ->> 'title', ''),
      nullif(data ->> 'number', ''),
      nullif(trim(concat_ws(' ', data ->> 'first_name', data ->> 'last_name')), ''),
      nullif(data ->> 'display_name', ''),
      nullif(data ->> 'email', ''),
      nullif(data ->> 'app_key', ''),
      ''
    ), 200),
    case when tg_table_name in ('contacts', 'staff') then (data ->> 'id')::uuid
         else coalesce((data ->> 'contact_id')::uuid, (data ->> 'staff_id')::uuid) end,
    diff
  );
  return null;
end;
$$;

revoke all on function private.record_audit_event() from public, anon, authenticated;

do $$
declare
  t text;
begin
  foreach t in array array[
    'client_staff_preferences', 'client_lists', 'client_list_members', 'care_plans', 'client_goals',
    'client_observations', 'client_tasks', 'client_documents', 'client_contacts', 'staff_leave',
    'staff_availability', 'staff_finance', 'record_notes', 'saved_views'
  ]
  loop
    execute format(
      'create trigger record_audit_event after insert or update or delete on public.%I '
      'for each row execute function private.record_audit_event()',
      t
    );
  end loop;
end;
$$;
