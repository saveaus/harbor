create type public.staff_preference as enum ('preferred', 'excluded');
create type public.goal_status as enum ('not_started', 'in_progress', 'achieved');
create type public.observation_kind as enum ('caution', 'incident');
create type public.observation_severity as enum ('low', 'medium', 'high', 'critical');
create type public.task_status as enum ('todo', 'in_progress', 'done');
create type public.document_folder as enum ('general', 'assessment', 'secure');
create type public.assessment_type as enum ('home', 'risk', 'mobility', 'falls', 'clinical', 'general');
create type public.client_contact_kind as enum ('contact', 'health_professional', 'roster_recipient');
create type public.professional_type as enum ('general_practitioner', 'specialist', 'case_manager', 'therapist');
create type public.document_review as enum ('pending', 'approved', 'declined');
create type public.leave_kind as enum ('annual', 'personal', 'sick');
create type public.leave_status as enum ('pending', 'accepted', 'rejected');

